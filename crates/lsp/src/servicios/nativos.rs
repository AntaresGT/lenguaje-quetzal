pub fn por_tipo(tipo: &TipoSemantico) -> Option<CatalogoNativo> {
    match tipo {
        TipoSemantico::Texto => Some(CatalogoNativo::nuevo("texto", TEXTO, VACIO)),
        TipoSemantico::Entero | TipoSemantico::Numero => {
            Some(CatalogoNativo::nuevo("número", NUMERO, VACIO))
        }
        TipoSemantico::Log => Some(CatalogoNativo::nuevo("log", LOG, VACIO)),
        TipoSemantico::Lista(_) => Some(CatalogoNativo::nuevo("lista", LISTA, VACIO)),
        TipoSemantico::Jsn => Some(CatalogoNativo::nuevo("jsn", JSN, VACIO)),
        TipoSemantico::Objeto(nombre) => por_nombre(nombre),
        _ => None,
    }
}

pub fn por_nombre(nombre: &str) -> Option<CatalogoNativo> {
    let catalogo = match nombre {
        "consola" => CatalogoNativo::nuevo("consola", CONSOLA, VACIO),
        "Matemática" | "Matematica" => {
            CatalogoNativo::nuevo("Matemática", MATEMATICA, &["E", "PI", "TAU"])
        }
        "Tiempo" => CatalogoNativo::nuevo("Tiempo", TIEMPO, VACIO),
        "ExpresiónRegular" | "ExpresionRegular" => {
            CatalogoNativo::nuevo("ExpresiónRegular", EXPRESION_REGULAR, VACIO)
        }
        "SistemaArchivos" => CatalogoNativo::nuevo("SistemaArchivos", SISTEMA_ARCHIVOS, VACIO),
        "Archivo" => CatalogoNativo::nuevo("Archivo", ARCHIVO, VACIO),
        "Bits" => CatalogoNativo::nuevo("Bits", BITS, VACIO),
        "Flujo" => CatalogoNativo::nuevo("Flujo", FLUJO, VACIO),
        "Observador" => CatalogoNativo::nuevo("Observador", OBSERVADOR, VACIO),
        "EventoArchivo" => CatalogoNativo::nuevo("EventoArchivo", EVENTO_ARCHIVO, VACIO),
        "ServidorHttp" | "Enrutador" => CatalogoNativo::nuevo("módulo nativo", HTTP_RUTAS, VACIO),
        "ClienteHttp" => CatalogoNativo::nuevo("ClienteHttp", CLIENTE_HTTP, VACIO),
        "PeticionEntrante" => CatalogoNativo::nuevo("PeticionEntrante", PETICION, VACIO),
        "RespuestaSaliente" | "RespuestaHttp" => {
            CatalogoNativo::nuevo("módulo nativo", RESPUESTA, VACIO)
        }
        "Formulario" => CatalogoNativo::nuevo("Formulario", FORMULARIO, VACIO),
        "ParteArchivo" => CatalogoNativo::nuevo("ParteArchivo", PARTE_ARCHIVO, VACIO),
        "HttpCodigos" => CatalogoNativo::nuevo(
            "HttpCodigos",
            HTTP_CODIGOS,
            &[
                "ACEPTADO",
                "CREADO",
                "ERROR_INTERNO",
                "NO_AUTENTICADO",
                "NO_ENCONTRADO",
                "OK",
            ],
        ),
        _ => return None,
    };
    Some(catalogo)
}
